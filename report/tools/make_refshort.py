"""Generate Template/refshort.tex from Template/references.bib.

One line per entry:  \\defrefshort{key}{Surname et al., Year, Short title...}
Used by \\tablesources{...} (Template/refmacros.tex) to print a key under tables.
Run from the report root:  python tools/make_refshort.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIB = ROOT / "Template" / "references.bib"
OUT = ROOT / "Template" / "refshort.tex"
TITLE_WORDS = 6


def entries(text):
    """Yield (key, fields) for each @type{key, ...} entry, brace-aware."""
    i = 0
    while True:
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,").search(text, i)
        if not m:
            return
        depth, j = 1, m.end()
        while depth and j < len(text):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        body = text[m.end():j - 1]
        i = j
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        yield m.group(2), fields(body)


def fields(body):
    out, k = {}, 0
    for fm in re.finditer(r"(\w+)\s*=\s*", body):
        if fm.start() < k:
            continue
        name, j = fm.group(1).lower(), fm.end()
        if j < len(body) and body[j] == "{":
            depth, s = 1, j + 1
            j += 1
            while depth and j < len(body):
                depth += {"{": 1, "}": -1}.get(body[j], 0)
                j += 1
            val = body[s:j - 1]
        elif j < len(body) and body[j] == '"':
            e = body.index('"', j + 1)
            val, j = body[j + 1:e], e + 1
        else:
            e = re.compile(r"[,\n]").search(body, j)
            e = e.start() if e else len(body)
            val, j = body[j:e].strip(), e
        out[name] = " ".join(val.split())
        k = j
    return out


def split_and(s):
    parts, depth, cur, i = [], 0, "", 0
    while i < len(s):
        c = s[i]
        depth += {"{": 1, "}": -1}.get(c, 0)
        if depth == 0 and s[i:i + 5].lower() == " and ":
            parts.append(cur.strip())
            cur, i = "", i + 5
            continue
        cur += c
        i += 1
    if cur.strip():
        parts.append(cur.strip())
    return parts


def surname(a):
    if a.startswith("{") and a.endswith("}"):
        return a[1:-1]                      # corporate author, keep whole
    if "," in a:
        return a.split(",")[0].strip()
    return a.split()[-1]


def short_author(raw):
    if not raw:
        return ""
    names = [surname(a) for a in split_and(raw)]
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} and {names[1]}"
    return f"{names[0]} et al."


def short_title(t):
    t = t.strip()
    while t.startswith("{") and t.endswith("}"):
        t = t[1:-1]
    # drop protective braces that are not part of a command
    t = re.sub(r"(?<!\\)\{([^{}\\]*)\}", r"\1", t)
    words = t.split()
    if len(words) <= TITLE_WORDS:
        return t.rstrip(".")
    cut = " ".join(words[:TITLE_WORDS]).rstrip(",;:.")
    if cut.count("{") != cut.count("}"):        # never cut inside a group
        return t.rstrip(".")
    return cut + "..."


def main():
    text = BIB.read_text(encoding="utf-8")
    lines = ["% Generated by tools/make_refshort.py from references.bib. Do not edit."]
    n = 0
    for key, f in entries(text):
        author = short_author(f.get("author") or f.get("editor") or f.get("organization")
                              or f.get("institution") or "")
        year = f.get("year", "n.d.")
        title = short_title(f.get("title", ""))
        parts = [p for p in (author, year, title) if p]
        lines.append(f"\\defrefshort{{{key}}}{{{', '.join(parts)}}}")
        n += 1
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"refshort: {n} entries -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
